/**
 * Illustrated festival maps bundled with the app (generated by scripts/map/).
 * Keyed by festival code (not year): a festival held at the same place every year reuses one map.
 * Kept out of user data, so stored data can never point the app at an image URL.
 */
/** An official-map marker icon (toilet, info, …) moved onto the redrawn map. */
export interface MapMark {
  id: number
  kind: string
  zone: string
  lat: number
  lng: number
  /** Where the map draws the mark, when it draws it itself (a layer 3 badge): tapping there selects its pin. */
  tap?: TapArea
}

/** One image of the map, stretched onto its bounds. A map's layers stay separate images, drawn bottom first. */
export interface MapLayer {
  url: string
  bounds: LatLngBounds
}

export interface FestivalMap {
  layers: readonly MapLayer[]
  /** The whole map (every layer inside it). */
  bounds: LatLngBounds
  initialView: LatLngBounds
  /** How far in the images stay sharp; null = the default for raster images. */
  maxZoom: number | null
  /** Open zoomed in until the map fills the screen (a map whose surroundings are blank); false = open on the whole
   *  initial view (a map whose ground runs on in its background colour). */
  fillOnOpen: boolean
  attribution: string
  /** Shown around the image (it should match the drawing's own background); null = the default paper. */
  background: string | null
  anchors: Record<string, readonly [number, number]>
  /** Radius (m) around an anchor where the drawing shows the place (a stage, a gate): tapping there selects its pin. */
  anchorTaps: Record<string, number>
  marks: readonly MapMark[]
}

/** A layer as the metadata names it: an image file of the map's folder. */
interface LayerFile {
  file: string
  bounds: LatLngBounds
}
type MapMeta = Omit<FestivalMap, 'layers'> & { layerFiles: readonly LayerFile[] }

const isPair = (value: unknown): value is [number, number] =>
  Array.isArray(value) && value.length === 2 && value.every((n) => typeof n === 'number' && Number.isFinite(n))

function toBounds(value: unknown, label: string): LatLngBounds {
  if (!Array.isArray(value) || value.length !== 2 || !isPair(value[0]) || !isPair(value[1])) {
    throw new Error(`map metadata: ${label} must be [[south, west], [north, east]]`)
  }
  const [sw, ne] = value
  if (sw[0] >= ne[0] || sw[1] >= ne[1]) throw new Error(`map metadata: ${label} south-west must be below north-east`)
  return [sw, ne]
}

const isRadius = (value: unknown): value is number => typeof value === 'number' && value > 0 && value <= 200

function toTapArea(value: unknown, bounds: LatLngBounds): TapArea | null {
  const t = value as Partial<TapArea>
  const ok = typeof t.lat === 'number' && typeof t.lng === 'number' && isRadius(t.radius) && isInsideBounds({ lat: t.lat, lng: t.lng }, bounds)
  return ok ? { lat: t.lat!, lng: t.lng!, radius: t.radius! } : null
}

/** Validates the generator's JSON so a bad regeneration fails loudly instead of drawing a broken map. */
export function parseMapMeta(raw: {
  attribution?: unknown
  background?: unknown
  bounds?: unknown
  initialView?: unknown
  maxZoom?: unknown
  fillOnOpen?: unknown
  layers?: unknown
  anchors?: unknown
  anchorTaps?: unknown
  marks?: unknown
}): MapMeta {
  const bounds = toBounds(raw.bounds, 'bounds')
  const initialView = toBounds(raw.initialView, 'initialView')
  const layerFiles = (Array.isArray(raw.layers) ? raw.layers : []).map((value: unknown, i): LayerFile => {
    const layer = value as { file?: unknown; bounds?: unknown }
    if (typeof layer.file !== 'string' || !layer.file) throw new Error(`map metadata: layer ${i} needs a file`)
    const layerBounds = toBounds(layer.bounds, `layer ${layer.file} bounds`)
    const inside = layerBounds.every(([lat, lng]) => isInsideBounds({ lat, lng }, bounds))
    if (!inside) throw new Error(`map metadata: layer ${layer.file} must lie inside the map bounds`)
    return { file: layer.file, bounds: layerBounds }
  })
  const anchors = Object.entries(raw.anchors ?? {}).map(([key, value]) => {
    if (!isPair(value) || !isInsideBounds({ lat: value[0], lng: value[1] }, bounds)) {
      throw new Error(`map metadata: anchor ${key} must be a [lat, lng] inside the image`)
    }
    return [key, value] as const
  })
  const anchorTaps = Object.entries((raw.anchorTaps ?? {}) as Record<string, unknown>).map(([key, radius]) => {
    if (!anchors.some(([k]) => k === key) || !isRadius(radius)) throw new Error(`map metadata: anchor tap ${key} needs an anchor and a radius`)
    return [key, radius] as const
  })
  const marks = (Array.isArray(raw.marks) ? raw.marks : []).map((value: unknown): MapMark => {
    const m = value as Partial<MapMark>
    const tap = m.tap === undefined ? undefined : toTapArea(m.tap, bounds)
    if (tap === null) throw new Error(`map metadata: mark ${String(m.id)} has a bad tap area`)
    const ok =
      typeof m.id === 'number' &&
      typeof m.kind === 'string' &&
      typeof m.zone === 'string' &&
      typeof m.lat === 'number' &&
      typeof m.lng === 'number' &&
      isInsideBounds({ lat: m.lat, lng: m.lng }, bounds)
    if (!ok) throw new Error(`map metadata: mark ${String(m.id)} needs id, kind, zone and a lat/lng inside the image`)
    return { id: m.id!, kind: m.kind!, zone: m.zone!, lat: m.lat!, lng: m.lng!, ...(tap ? { tap } : {}) }
  })
  return {
    bounds,
    initialView,
    maxZoom: typeof raw.maxZoom === 'number' && Number.isFinite(raw.maxZoom) ? raw.maxZoom : null,
    fillOnOpen: raw.fillOnOpen !== false,
    layerFiles,
    marks,
    attribution: typeof raw.attribution === 'string' ? raw.attribution : '',
    background: typeof raw.background === 'string' && /^#[0-9a-f]{6}$/i.test(raw.background) ? raw.background : null,
    anchors: Object.fromEntries(anchors),
    anchorTaps: Object.fromEntries(anchorTaps),
  }
}

/** The map's images: the layers the metadata lists (by file name), or one image covering the whole map. */
export function withImages({ layerFiles, ...meta }: MapMeta, images: string | Readonly<Record<string, string>>): FestivalMap {
  if (typeof images === 'string') return { ...meta, layers: [{ url: images, bounds: meta.bounds }] }
  if (layerFiles.length === 0) throw new Error('map metadata: no layers listed')
  const layers = layerFiles.map(({ file, bounds }) => {
    const url = images[file]
    if (!url) throw new Error(`map metadata: layer ${file} is not bundled`)
    return { url, bounds }
  })
  return { ...meta, layers }
}

const MAPS: Record<string, FestivalMap> = {
  [GRAND_MINT_SERIES]: withImages(parseMapMeta(gmfMeta), gmfImage),
  // The layered map redrawn from the official site map (scripts/map/layers/pentaport/): the big area map's ground
  // under the venue map's ground, operations and pins.
  [PENTAPORT_SERIES]: withImages(parseMapMeta(pentaportMeta), {
    'big-layer1.svg': pentaportBigLayer1,
    'layer1.svg': pentaportLayer1,
    'layer2.svg': pentaportLayer2,
    'layer3.svg': pentaportLayer3,
  }),
}

/** The map of a festival code; use festivalMapFor (data/catalog) to go from a festival id. */
export const seriesMapFor = (seriesCode: string): FestivalMap | null => MAPS[seriesCode] ?? null
